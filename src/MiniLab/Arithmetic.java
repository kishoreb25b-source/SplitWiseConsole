package MiniLab;

public class Arithmetic {
    public static void main(String[] args) {

        System.out.println(17/5); //it print int because "int/int=int"
        //3

        System.out.println(17.0 / 5); // in this we divide "double/int=double" small type will change into big type
        //3.4
        System.out.println(17 % 5); // 5*3=15 15-17=2
        //2
    }
}
