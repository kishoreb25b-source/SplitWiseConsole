package MiniLab;

public class Loop {
    public static void main(String[] args) {

        System.out.println("for loop");
        for (int i=1; i < 6; i++) {
            System.out.println(i);
        }
        System.out.println("while loop");
        int j=5;
        while (j>=1){
            System.out.println(j);
            j--;
        }
    }

}
